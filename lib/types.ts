export type Gender = 'Nam' | 'Nữ' | 'Khác';
export type MapLocation = { address: string; latitude: number | null; longitude: number | null };
export type LunarAnniversary = { day: number; month: number; leap: boolean; missingLeap: 'regular' | 'skip'; missingDay: 'last' | 'skip' };
export type Member = {
  id: string;
  fullName: string;
  aliases: string[];
  birthOrder: number | null;
  gender: Gender;
  birthDate: string;
  deathDate: string;
  anniversary: LunarAnniversary | null;
  birthPlace: string;
  currentPlace: string;
  home: MapLocation;
  homePublic: boolean;
  zaloPhone: string;
  zaloConsent: boolean;
  occupation: string;
  biography: string;
  fatherId: string | null;
  motherId: string | null;
  spouseIds: string[];
  avatar: string;
  createdAt: string;
};
export type Shrine = { id: string; name: string; description: string; location: MapLocation; caretakerId: string | null; ceremony: LunarAnniversary | null; createdAt: string };
export type ReminderSubscription = { id: string; recipientId: string; eventKey: string; daysBefore: number; enabled: boolean; createdAt: string };
export type ReminderLog = { id: string; subscriptionId: string; eventDate: string; attemptedAt: string; status: 'pending' | 'sent' | 'failed'; detail: string };
export type NewsCategory = 'gio' | 'le' | 'tiec' | 'khac';
export type ContentRecord = {
  id: string;
  kind: 'document' | 'event';
  category?: NewsCategory;
  title: string;
  description: string;
  date: string;
  location: string;
  author?: string;
  fileUrl: string;
  images?: string[];
  createdAt: string;
};
export type FamilyData = { members: Member[]; shrines: Shrine[]; reminders: ReminderSubscription[]; reminderLogs: ReminderLog[]; content: ContentRecord[]; updatedAt: string };
